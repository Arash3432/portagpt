export const dict: Record<Locale, Dict> = { fa, en, ar, zh };

export function tr(locale: Locale): Dict {
  return dict[locale] ?? fa;
}

export function localeTag(locale: Locale): string {
  return localeMeta[locale]?.tag || "fa-IR";
}

export function fmtNum(locale: Locale, value: number): string {
  try {
    return new Intl.NumberFormat(localeTag(locale)).format(value);
  } catch {
    return String(value);
  }
}

export function fmtDate(
  locale: Locale,
  value: string | Date,
  options: Intl.DateTimeFormatOptions = { dateStyle: "short" },
): string {
  try {
    return new Intl.DateTimeFormat(localeTag(locale), options).format(new Date(value));
  } catch {
    return "";
  }
}

export function fill(template: string, values: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (match, key: string) =>
    key in values ? String(values[key]) : match,
  );
}
